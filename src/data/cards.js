export const CARD_LIST = Object.values(CARDS);

export function getDefaultStarterDeck() {
  const deck = [];
  for (const card of CARD_LIST) {
    for (let i = 0; i < (card.starterCount || 0); i++) {
      deck.push(card.id);
    }
  }
  return deck; // 14 cards, includes Porta x2, Pyro x2, Aqua x2, Aegis x2, Fulmen, Ventus, Terra, Lux, Axe of 10,000 Souls, Kurenos
}
